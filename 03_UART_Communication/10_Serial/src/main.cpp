/*=======================================================*/
// Serial : 시리얼로 PC 에 한 줄 보내기
//
// 교재 4장 실습 4-1. 마이크로컨트롤러에는 화면이 없다. 내부 상태를 보려면
// 통신을 하나 살려 두고 PC 터미널로 내보내야 한다. 그 첫걸음이다.
//
// 연결 없음. 0·1번 핀(RX·TX)이 보드 안에서 USB 변환 칩에 이어져 있다.
// Serial.begin() 을 부르는 순간 0·1번은 GPIO 가 아니라 USART 가 된다.
//
// 시리얼 모니터를 9600 bps 로 열어야 글자가 제대로 보인다.
// 속도가 다르면 깨진 글자가 나온다.
//
// 선행 학습 : 01_Digital_IO/50_Bit_Mask      다음 단계 : 12_UART_Scope
/*=======================================================*/
#include <Arduino.h>

void setup()
{
  Serial.begin(9600);       // 0·1번 핀을 USART 로 넘기고 속도를 약속한다
}

void loop()
{
  Serial.println("Hello Arduino !");
  delay(1000);
}
